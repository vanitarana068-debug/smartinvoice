-- Run this once in the Supabase SQL Editor for your project.
-- All application records are isolated by Supabase Auth user ID.

create table if not exists public.settings (
  user_id uuid primary key references auth.users(id) on delete cascade,
  business_name text not null default '',
  currency text not null default 'USD' check (currency ~ '^[A-Z]{3}$'),
  opening_cash_balance numeric(14, 2),
  opening_balance_date date not null default current_date
);

create table if not exists public.customers (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  email text not null default '',
  company text not null default '',
  created_at timestamptz not null default now(),
  unique (user_id, id)
);

create table if not exists public.invoices (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  customer_id bigint not null,
  number text not null,
  description text not null default '',
  amount numeric(14, 2) not null check (amount > 0),
  issue_date date not null,
  due_date date not null,
  status text not null check (status in ('draft', 'sent', 'paid', 'overdue')),
  created_at timestamptz not null default now(),
  service_category text not null default 'General services',
  unique (user_id, number),
  unique (user_id, id),
  foreign key (user_id, customer_id)
    references public.customers(user_id, id) on delete restrict
);

create table if not exists public.expenses (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  category text not null,
  description text not null default '',
  amount numeric(14, 2) not null check (amount > 0),
  expense_date date not null,
  created_at timestamptz not null default now(),
  service_category text not null default ''
);

create table if not exists public.payments (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  invoice_id bigint not null,
  amount numeric(14, 2) not null check (amount > 0),
  paid_at date not null,
  method text not null default 'Bank transfer',
  created_at timestamptz not null default now(),
  foreign key (user_id, invoice_id)
    references public.invoices(user_id, id) on delete cascade
);

create table if not exists public.reminders (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  invoice_id bigint not null,
  sent_at timestamptz not null default now(),
  foreign key (user_id, invoice_id)
    references public.invoices(user_id, id) on delete cascade
);

create index if not exists idx_customers_user on public.customers(user_id);
create index if not exists idx_invoices_user_dates on public.invoices(user_id, issue_date, due_date);
create index if not exists idx_expenses_user_date on public.expenses(user_id, expense_date);
create index if not exists idx_payments_user_date on public.payments(user_id, paid_at);
create index if not exists idx_reminders_user_invoice on public.reminders(user_id, invoice_id);

alter table public.settings enable row level security;
alter table public.customers enable row level security;
alter table public.invoices enable row level security;
alter table public.expenses enable row level security;
alter table public.payments enable row level security;
alter table public.reminders enable row level security;

